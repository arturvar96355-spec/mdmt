/** Русская типографика: неразрывные пробелы, «ёлочки», тире, ₽. */
const NBSP = ' ';

const SHORT = /(^|[\s(«"])([А-Яа-яЁёA-Za-z]{1,2})\s+/g;

export function typograph(input: string): string {
  let s = input;
  // кавычки "..." -> «...»
  s = s.replace(/"([^"]+)"/g, '«$1»');
  // дефис между пробелами -> длинное тире
  s = s.replace(/\s[-–]\s/g, `${NBSP}— `);
  // предлоги и союзы из 1–2 букв (дважды — для подряд идущих)
  s = s.replace(SHORT, `$1$2${NBSP}`).replace(SHORT, `$1$2${NBSP}`);
  // число и единица
  s = s.replace(/(\d)\s+(мм|м|кг|т|₽|руб\.?|шт\.?|лет|года|год|%|кН)(?![А-Яа-яA-Za-z])/g, `$1${NBSP}$2`);
  // разряды в числах
  s = s.replace(/(\d)\s(\d{3})(?!\d)/g, `$1${NBSP}$2`);
  return s;
}
